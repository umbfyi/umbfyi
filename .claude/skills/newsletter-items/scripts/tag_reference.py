"""Build references/tags.md: how each tag has actually been used in published newsletters.

Matt's tagging is hard to put into rules, so past issues are the rules. For each tag this lists
how often it was used, in which groups, what it was paired with, the tag-map.json patterns that
auto-assign it, and recent example titles, so new items can be tagged by analogy with what was
done before. Tags in the tag map but not used lately, and one-off tags outside it, are listed too.

Usage (from the repo root):
    .claude/skills/process-tips/scripts/umbfyi.sh featured-all <from-iso-date> > featured.json
    python3 -I .claude/skills/newsletter-items/scripts/tag_reference.py featured.json \
        > .claude/skills/newsletter-items/references/tags.md
"""

import json
import sys
import urllib.request
from collections import Counter, defaultdict

TAG_MAP_URL = "https://raw.githubusercontent.com/umbfyi/umbfyi/HEAD/data/tag-map.json"
EXAMPLES_PER_TAG = 4
MIN_USES = 2


def main(path):
    with open(path, encoding="utf-8") as f:
        items = json.load(f)

    # Tag -> tag-map category (product, topic, event, ...), for grouping the output.
    try:
        with urllib.request.urlopen(TAG_MAP_URL, timeout=20) as r:
            tag_map = json.load(r)
        category_of = {tag: cat for cat, tags in tag_map.items() for tag in tags}
        patterns_of = {tag: pats for tags in tag_map.values() for tag, pats in tags.items()}
    except Exception:
        category_of = {}
        patterns_of = {}

    items.sort(key=lambda x: x["newsletterDate"], reverse=True)
    uses = Counter()
    groups = defaultdict(Counter)
    pairs = defaultdict(Counter)
    examples = defaultdict(list)
    untagged = Counter()
    per_group = Counter()

    for item in items:
        tags = sorted(set(t.lower() for t in item.get("tags") or []))
        group = item.get("group") or "?"
        per_group[group] += 1
        if not tags:
            untagged[group] += 1
        for tag in tags:
            uses[tag] += 1
            groups[tag][group] += 1
            for other in tags:
                if other != tag:
                    pairs[tag][other] += 1
            if len(examples[tag]) < EXAMPLES_PER_TAG:
                others = [t for t in tags if t != tag]
                suffix = f" (+{', '.join(others)})" if others else ""
                examples[tag].append(f"{item['title']}{suffix}")

    dates = [i["newsletterDate"][:10] for i in items]
    out = []
    out.append("# Tags as used in past newsletters")
    out.append("")
    out.append(f"Generated by `scripts/tag_reference.py` from {len(items)} published items, "
               f"{min(dates)} to {max(dates)}. Regenerate rather than edit by hand.")
    out.append("")
    out.append("## How many tags per item")
    out.append("")
    counts = Counter(len(set(i.get("tags") or [])) for i in items)
    out.append(", ".join(f"{n} tags: {c}" for n, c in sorted(counts.items())))
    out.append("")
    out.append("Untagged share by group: " + ", ".join(
        f"{g} {round(100 * untagged[g] / per_group[g])}%" for g, _ in per_group.most_common() if per_group[g] >= 20))
    out.append("")

    by_category = defaultdict(list)
    for tag, n in uses.most_common():
        if n >= MIN_USES:
            by_category[category_of.get(tag, "other (not in tag-map.json)")].append(tag)

    for category in sorted(by_category, key=lambda c: (c.startswith("other"), c)):
        out.append(f"## {category}")
        out.append("")
        for tag in by_category[category]:
            group_text = ", ".join(f"{g} {c}" for g, c in groups[tag].most_common(3))
            pair_text = ", ".join(t for t, _ in pairs[tag].most_common(3))
            out.append(f"### `{tag}` ({uses[tag]})")
            out.append(f"Groups: {group_text}." + (f" Often with: {pair_text}." if pair_text else ""))
            if tag in patterns_of:
                out.append("Auto-assigned by: " + ", ".join(f"`{p}`" for p in patterns_of[tag]))
            for ex in examples[tag]:
                out.append(f"- {ex}")
            out.append("")

    unused = sorted(t for t in patterns_of if uses[t] < MIN_USES)
    if unused:
        out.append("## In the tag map, but used less than twice in this period")
        out.append("")
        for tag in unused:
            out.append(f"- `{tag}` ({category_of[tag]}): " + ", ".join(f"`{p}`" for p in patterns_of[tag]))
        out.append("")

    rare = sorted(t for t, n in uses.items() if n < MIN_USES)
    if rare:
        out.append("## Used once")
        out.append("")
        out.append(", ".join(f"`{t}`" for t in rare))
        out.append("")

    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
